"""Generate single-file Supabase Dashboard deployments from the tested handlers."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files are stale')
    args = parser.parse_args()
    source = (ROOT / 'supabase/functions/_shared/billing.mjs').read_text()
    for slug, handler in [('create-survey-checkout', 'createCheckout'), ('stripe-survey-webhook', 'stripeWebhook')]:
        path = ROOT / 'supabase/dashboard' / (slug + '.ts')
        content = ('// @ts-nocheck\n'
                   '// Generated by scripts/build_dashboard_functions.py. Edit the shared source instead.\n'
                   '// Paste this whole file into index.ts in the Supabase Dashboard editor.\n'
                   '// Disable the gateway JWT check; authentication is verified inside the handler.\n'
                   + source + '\nDeno.serve((request) => ' + handler
                   + '(request, { env: (name) => Deno.env.get(name) }));\n')
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale dashboard deployment: {path.relative_to(ROOT)}. Run this script without --check.')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)

if __name__ == '__main__':
    main()
